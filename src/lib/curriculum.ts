// ================= Басқа пәндер мен параллельдер =================
// Жол: [бөлім, қазақша атауы, орысша атауы, жоспарлы сағат, тірек тақырыптың реттік нөмірі (1-ден) немесе 0]
type Row = [string, string, string, number, number];

function build(prefix: string, sections: Record<string, L10n>, rows: Row[]): Topic[] {
  return rows.map(([sec, kk, ru, h, pre], i) => T(`${prefix}${String(i + 1).padStart(2, '0')}`, sections[sec], h, kk, ru, pre ? [`${prefix}${String(pre).padStart(2, '0')}`] : []));
}

